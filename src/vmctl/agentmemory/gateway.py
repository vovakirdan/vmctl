"""Standalone root helper for the forced-command memory administration SSH key.

Deployment config is root-owned /etc/agentmemory/gateway.json. No caller-supplied
command, filename or backend address is accepted. Requests and secrets use stdin.
"""

import json
import os
import re
import stat
import subprocess
import sys
import tempfile
from collections.abc import Mapping
from ipaddress import IPv4Address
from pathlib import Path
from typing import Any
from urllib.request import Request, urlopen

ROOT_UID = 0
CONFIG = Path("/etc/agentmemory/gateway.json")
CLIENT_ID = re.compile(r"vmctl-([1-8][0-9]{2,3}|9[0-9]{2})-([0-9a-f]{32})")
WORKSTATION_ID = re.compile(r"workstation-([a-z][a-z0-9-]{0,31})-([0-9a-f]{32})")
SECRET = re.compile(r"[A-Za-z0-9_-]{48,128}")


class GatewayError(Exception):
    """Safe public error; underlying exceptions are never returned over SSH."""


def atomic(path: Path, content: bytes, mode: int, gid: int = -1) -> None:
    descriptor, temporary = tempfile.mkstemp(prefix=".vmctl-memory-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            os.fchmod(stream.fileno(), mode)
            if gid != -1:
                os.fchown(stream.fileno(), -1, gid)
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
        directory = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        Path(temporary).unlink(missing_ok=True)


def private_json(path: Path) -> dict[str, Any]:
    details = path.lstat()
    if not stat.S_ISREG(details.st_mode) or details.st_uid != ROOT_UID or details.st_mode & 0o077:
        raise GatewayError("Gateway private configuration permissions are invalid")
    value = json.loads(path.read_text())
    if not isinstance(value, dict):
        raise GatewayError("Gateway private configuration is invalid")
    return value


def validate_identity(client_id: str, owner: str) -> None:
    workstation = WORKSTATION_ID.fullmatch(client_id)
    if workstation is not None:
        if owner != f"workstation:{workstation[2]}":
            raise GatewayError("Client ownership metadata is invalid")
        return
    match = CLIENT_ID.fullmatch(client_id)
    if match is None or not 100 <= int(match[1]) < 9000 or owner != f"vmctl:{match[2]}":
        raise GatewayError("Client ownership metadata is invalid")


def render(config: Mapping[str, Any], clients: Mapping[str, Any], backend_secret: str) -> bytes:
    host = str(config["endpoint_host"])
    IPv4Address(host)
    port = int(config.get("endpoint_port", 443))
    if not 1 <= port <= 65535 or not SECRET.fullmatch(backend_secret):
        raise GatewayError("Gateway endpoint or backend credential is invalid")
    lines = [
        "# Generated by vmctl. Do not edit; secrets must remain private.",
        "{",
        "  admin localhost:2019",
        "  auto_https disable_redirects",
        "}",
        f"https://{host}:{port} {{",
        "  tls internal",
    ]
    for index, (client_id, record) in enumerate(sorted(clients.items())):
        if not isinstance(record, dict):
            raise GatewayError("Gateway client registry is invalid")
        validate_identity(client_id, record.get("owner", ""))
        secret = record.get("secret", "")
        address = str(IPv4Address(record.get("address", "")))
        if not isinstance(secret, str) or not SECRET.fullmatch(secret):
            raise GatewayError("Gateway client registry is invalid")
        lines.extend(
            [
                f"  @client{index} {{",
                f"    remote_ip {address}/32",
                f'    header Authorization "Bearer {secret}"',
                "  }",
                f"  handle @client{index} {{",
                "    reverse_proxy 127.0.0.1:3111 {",
                f'      header_up Authorization "Bearer {backend_secret}"',
                "    }",
                "  }",
            ]
        )
    lines.extend(['  respond "Unauthorized" 401', "}", ""])
    return "\n".join(lines).encode()


def run(arguments: list[str]) -> None:
    try:
        completed = subprocess.run(arguments, capture_output=True, timeout=30, check=False)
    except (OSError, subprocess.SubprocessError):
        raise GatewayError("Gateway validation or reload failed") from None
    if completed.returncode:
        raise GatewayError("Gateway validation or reload failed")


def backend_ready(secret: str) -> None:
    request = Request(
        "http://127.0.0.1:3111/agentmemory/health", headers={"Authorization": f"Bearer {secret}"}
    )
    try:
        with urlopen(request, timeout=5) as response:
            if response.status != 200:
                raise GatewayError("Memory backend is unavailable")
    except (OSError, ValueError):
        raise GatewayError("Memory backend is unavailable") from None


def apply(config: Mapping[str, Any], clients: dict[str, Any], backend_secret: str) -> None:
    state_path, caddy_path = Path(config["clients_file"]), Path(config["caddy_file"])
    import grp

    group = grp.getgrnam("caddy").gr_gid
    candidate = caddy_path.with_name(".vmctl-memory-candidate")
    previous_state = state_path.read_bytes() if state_path.exists() else None
    previous_caddy = caddy_path.read_bytes() if caddy_path.exists() else None
    payload = render(config, clients, backend_secret)
    try:
        atomic(candidate, payload, 0o640, group)
        run(
            [
                "runuser",
                "-u",
                "caddy",
                "--",
                "caddy",
                "validate",
                "--adapter",
                "caddyfile",
                "--config",
                str(candidate),
            ]
        )
        try:
            atomic(state_path, json.dumps(clients, sort_keys=True).encode(), 0o600)
            atomic(caddy_path, payload, 0o640, group)
            run(["systemctl", "reload", "caddy"])
        except (GatewayError, OSError):
            # Restore both persistent files and the running configuration before reporting failure.
            if previous_state is None:
                state_path.unlink(missing_ok=True)
            else:
                atomic(state_path, previous_state, 0o600)
            if previous_caddy is None:
                caddy_path.unlink(missing_ok=True)
            else:
                atomic(caddy_path, previous_caddy, 0o640, group)
                run(["systemctl", "reload", "caddy"])
            raise GatewayError(
                "Gateway change failed; inspect server state before retrying"
            ) from None
    finally:
        candidate.unlink(missing_ok=True)


def process(config: Mapping[str, Any], request: Mapping[str, Any]) -> None:
    operation = request.get("operation")
    expected = {"operation"} if operation == "preflight" else {"operation", "client_id", "owner"}
    if operation == "grant":
        expected |= {"secret", "address"}
    elif operation == "revoke" and "secret" in request:
        expected.add("secret")
    if operation not in {"preflight", "grant", "revoke"} or set(request) != expected:
        raise GatewayError("Unsupported gateway request")
    secret_path = Path(config["backend_secret_file"])
    details = secret_path.lstat()
    if not stat.S_ISREG(details.st_mode) or details.st_uid != ROOT_UID or details.st_mode & 0o077:
        raise GatewayError("Backend credential permissions are invalid")
    backend_secret = secret_path.read_text().strip()
    if not SECRET.fullmatch(backend_secret):
        raise GatewayError("Backend credential is invalid")
    if operation != "revoke":
        backend_ready(backend_secret)
    state_path = Path(config["clients_file"])
    clients = private_json(state_path) if state_path.exists() else {}
    render(config, clients, backend_secret)
    if operation == "preflight":
        return
    client_id, owner = request["client_id"], request["owner"]
    if not isinstance(client_id, str) or not isinstance(owner, str):
        raise GatewayError("Client ownership metadata is invalid")
    validate_identity(client_id, owner)
    existing = clients.get(client_id)
    if existing is not None and existing.get("owner") != owner:
        raise GatewayError("Client is owned by another invocation")
    if operation == "revoke" and existing is not None and "secret" in request:
        import hmac

        if not isinstance(request["secret"], str) or not hmac.compare_digest(
            existing.get("secret", ""), request["secret"]
        ):
            raise GatewayError("Rollback credential does not match the owned client")
    if operation == "grant":
        address = str(IPv4Address(request["address"]))
        secret = request["secret"]
        if not isinstance(secret, str) or not SECRET.fullmatch(secret):
            raise GatewayError("Invalid client credential")
        record = {"owner": owner, "address": address, "secret": secret}
        if existing is not None and existing != record:
            raise GatewayError("Refusing to replace an existing client")
        if any(
            value.get("address") == address and key != client_id for key, value in clients.items()
        ):
            raise GatewayError("Client address is already authorized")
        clients[client_id] = record
    else:
        clients.pop(client_id, None)
    apply(config, clients, backend_secret)


def main() -> int:
    import fcntl

    try:
        raw = sys.stdin.buffer.read(8193)
        if len(raw) > 8192:
            raise GatewayError("Gateway request is too large")
        request = json.loads(raw)
        if not isinstance(request, dict):
            raise GatewayError("Invalid gateway request")
        config = private_json(CONFIG)
        lock_path = Path(config["clients_file"]).with_suffix(".lock")
        with lock_path.open("a") as lock:
            os.chmod(lock_path, 0o600)
            fcntl.flock(lock, fcntl.LOCK_EX)
            process(config, request)
        print('{"ok":true}')
        return 0
    except (GatewayError, OSError, ValueError, TypeError, KeyError, subprocess.SubprocessError):
        print('{"ok":false}')
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
